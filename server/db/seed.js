function seed() {
  migrate();

  const adminPassword = process.env.SEED_ADMIN_PASSWORD || 'admin123';
  const exists = db.prepare('SELECT id FROM users WHERE username = ?').get('admin');
  if (!exists) {
    db.prepare('INSERT INTO users (username, password_hash, real_name, role) VALUES (?, ?, ?, ?)')
      .run('admin', bcrypt.hashSync(adminPassword, 10), '系统管理员', 'admin');
    console.log('已创建初始管理员账号 admin（初始密码见部署说明，请登录后立即修改）');
  }

  const insert = db.prepare('INSERT OR IGNORE INTO dictionaries (dict_type, name) VALUES (?, ?)');
  const insertAll = db.transaction((type, names) => {
    for (const name of names) insert.run(type, name);
  });
  insertAll('disease', diseases);
  insertAll('herb', herbs);
  insertAll('syndrome', syndromes);
  insertAll('formula', formulas);

  const count = (t) => db.prepare('SELECT COUNT(*) AS c FROM dictionaries WHERE dict_type = ?').get(t).c;
  console.log(`字典初始化完成：疾病 ${count('disease')} 条，中药 ${count('herb')} 条，证型 ${count('syndrome')} 条，方剂 ${count('formula')} 条`);
}

if (require.main === module) seed();
module.exports = seed;
